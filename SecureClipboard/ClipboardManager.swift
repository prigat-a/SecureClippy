import Foundation
import CryptoKit
import AppKit

/// Watches the general pasteboard and keeps an in-memory, encrypted history.
///
/// Plaintext is never stored: each entry holds only its AES-GCM ciphertext and a
/// SHA-256 digest (used to skip duplicates). Text is decrypted on demand, only
/// when the unlocked UI shows it or copies it back to the pasteboard.
final class ClipboardManager: ObservableObject {
    @Published private(set) var clipboardItems: [ClipboardItem] = []

    /// Entries older than this are dropped.
    let maxItemAge: TimeInterval = 24 * 60 * 60
    /// Upper bound on history length, so memory doesn't grow without limit.
    let maxItemCount = 200

    /// Pasteboard types that password managers and other apps use to say
    /// "don't record this" (see nspasteboard.org).
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    private let encryptionKey = SymmetricKey(size: .bits256)
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var pollTimer: Timer?
    private var cleanupTimer: Timer?

    init() {
        // Start from the current state so whatever was already on the
        // clipboard at launch isn't recorded (and isn't cleared either).
        lastChangeCount = pasteboard.changeCount

        pollTimer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.checkClipboard()
        }
        cleanupTimer = Timer.scheduledTimer(withTimeInterval: 60 * 60, repeats: true) { [weak self] _ in
            self?.removeExpiredItems()
        }
        // Generous tolerance lets macOS coalesce these wakeups with other work,
        // which keeps idle CPU/energy use near zero.
        pollTimer?.tolerance = 0.25
        cleanupTimer?.tolerance = 5 * 60
    }

    deinit {
        pollTimer?.invalidate()
        cleanupTimer?.invalidate()
    }

    // MARK: - Monitoring

    private func checkClipboard() {
        // changeCount is cheap to read; only touch the contents when it moves.
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        if let types = pasteboard.types, !Self.ignoredTypes.isDisjoint(with: types) { return }
        guard let string = pasteboard.string(forType: .string), !string.isEmpty else { return }

        let plaintext = Data(string.utf8)
        let digest = Data(SHA256.hash(data: plaintext))

        // Copying the same text again moves it to the top instead of duplicating it.
        clipboardItems.removeAll { $0.digest == digest }

        guard let sealed = try? AES.GCM.seal(plaintext, using: encryptionKey).combined else { return }
        clipboardItems.insert(ClipboardItem(encryptedContent: sealed, digest: digest), at: 0)

        if clipboardItems.count > maxItemCount {
            clipboardItems.removeLast(clipboardItems.count - maxItemCount)
        }
    }

    // MARK: - Access

    /// Decrypts an entry's text. Returns nil if the ciphertext can't be opened.
    func content(of item: ClipboardItem) -> String? {
        guard let box = try? AES.GCM.SealedBox(combined: item.encryptedContent),
              let data = try? AES.GCM.open(box, using: encryptionKey) else { return nil }
        return String(data: data, encoding: .utf8)
    }

    func copyToClipboard(_ item: ClipboardItem) {
        guard let string = content(of: item) else { return }
        pasteboard.clearContents()
        pasteboard.setString(string, forType: .string)
        // Our own write isn't new history; just bump the entry to the top.
        lastChangeCount = pasteboard.changeCount
        if let index = clipboardItems.firstIndex(where: { $0.id == item.id }) {
            clipboardItems.insert(clipboardItems.remove(at: index), at: 0)
        }
    }

    func removeItem(_ item: ClipboardItem) {
        clipboardItems.removeAll { $0.id == item.id }
    }

    func removeAll() {
        clipboardItems.removeAll()
    }

    private func removeExpiredItems() {
        let cutoff = Date().addingTimeInterval(-maxItemAge)
        clipboardItems.removeAll { $0.timestamp < cutoff }
    }
}

struct ClipboardItem: Identifiable {
    let id = UUID()
    let encryptedContent: Data
    /// SHA-256 of the plaintext, for de-duplication without keeping the text.
    let digest: Data
    let timestamp = Date()
}
